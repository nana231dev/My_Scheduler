"""24절기 계산 유틸리티 (2026-09-04 버전 통합 시 core 패키지로 추출)"""


class SolarTerms:
    """양력 날짜를 기준으로 24절기를 반환하는 클래스"""

    def get_solar_term(self, month, day):
        terms_map = {
            1: [("소한", 5), ("대한", 20)],
            2: [("입춘", 4), ("우수", 19)],
            3: [("경칩", 5), ("춘분", 20)],
            4: [("청명", 4), ("곡우", 20)],
            5: [("입하", 5), ("소만", 21)],
            6: [("망종", 5), ("하지", 21)],
            7: [("소서", 7), ("대서", 22)],
            8: [("입추", 7), ("처서", 23)],
            9: [("백로", 7), ("추분", 23)],
            10: [("한로", 8), ("상강", 23)],
            11: [("입동", 7), ("소설", 22)],
            12: [("대설", 7), ("동지", 21)]
        }
        if month in terms_map:
            for term_name, term_day in terms_map[month]:
                if day == term_day:
                    return term_name
        return None
