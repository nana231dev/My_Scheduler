def get_all() -> list[tuple[str, str, str, str]]:
    """전체 공식 목록."""
    return list(F)


def count() -> int:
    """공식 총개수."""
    return len(F)


def get_categories() -> list[str]:
    """분야 목록."""
    return sorted({row[0] for row in F})


def get_by_level(level: str) -> list[tuple[str, str, str, str]]:
    """주가(초등/중등/고등/대학) 필터."""
    return [row for row in F if row[1] == level]


def get_by_category(category: str) -> list[tuple[str, str, str, str]]:
    """분야 필터."""
    return [row for row in F if row[0] == category]


def search(keyword: str) -> list[tuple[str, str, str, str]]:
    """이름/식/분야 키워드 검색 (대소문자 무관)."""
    kw = keyword.strip().lower()
    if not kw:
        return list(F)
    return [row for row in F if any(kw in str(c).lower() for c in row)]

